#!/usr/bin/env python3
"""
Embedding Extraction Script for hIPSC_CM dataset using MIMIC (Frozen Encoder)
=============================================================================
This script:
1. Loads the precomputed hIPSC_CM dataset exclusively from Parquet:
   /beegfs/prj/RNA_NLP/FlorianMasterThesis/code/data/hIPSC_CM/hIPSC_CM_mrna_protein.parquet
   (Generated by reconstruct_proteins_hIPSC_CM.py; strictly no fallbacks).
2. Reads precomputed clean RNA sequences (clean_rna_seq), protein sequences (protein_seq_clean),
   and CDS tracks (cds) directly from Parquet.
3. Supports 3 embedding modes (for training 3 downstream Ridge Regressions):
   - 'rna': Uses only RNA nucleotide sequence (clean_rna_seq) -> 9216-dim embedding.
   - 'protein': Uses only reconstructed protein sequence (protein_seq_clean) -> 9216-dim embedding.
   - 'rna_protein': Joint multimodal conditioning (clean_rna_seq + protein_seq_clean) -> 10752-dim embedding.
   - 'all': Generates all 3 sets of embeddings in one run!
4. Saves all embeddings and metadata in compressed NPZ archives at:
   /beegfs/prj/RNA_NLP/FlorianMasterThesis/code/data/hIPSC_CM/mimic/
   - mimic_embeddings_hIPSC_CM_rna.npz
   - mimic_embeddings_hIPSC_CM_protein.npz
   - mimic_embeddings_hIPSC_CM_rna_protein.npz

Usage:
------
# 1. Generate all 3 embedding sets in one run:
python scripts/extract_embeddings_hIPSC_CM.py --mode all

# 2. Or generate individual modes:
python scripts/extract_embeddings_hIPSC_CM.py --mode rna
python scripts/extract_embeddings_hIPSC_CM.py --mode protein
python scripts/extract_embeddings_hIPSC_CM.py --mode rna_protein

# Optional: With local weights directory:
python scripts/extract_embeddings_hIPSC_CM.py --mode all --weights_dir /path/to/mimic_weights
"""

